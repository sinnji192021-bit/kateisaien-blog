def main():
    ok = 0
    for path, anchor, html, where in EDITS:
        s = io.open(path, encoding='utf-8').read()
        n = s.count(anchor)
        if n != 1:
            print("✗ アンカーが%d件: %s | %s" % (n, path, anchor[:50]))
            continue
        if '★' in html:
            print("✗ 追記に★が混入: %s" % path)
            continue
        s = s.replace(anchor, html + anchor if where == "before" else anchor + html, 1)
        io.open(path, 'w', encoding='utf-8').write(s)
        print("✓ %s ← %s" % (path, anchor.strip()[:44]))
        ok += 1
    print("\n反映: %d / %d" % (ok, len(EDITS)))


main()
